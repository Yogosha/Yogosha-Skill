#!/usr/bin/env python3
"""
Generate the per-agent adapter files from RULES.md.

RULES.md is the single source of truth. Each adapter is a tool-specific header
followed by the body of RULES.md, so the methodology never forks. Run this after
editing RULES.md, and run it with --check in CI to fail when an adapter drifted.

    python scripts/build_adapters.py          # rewrite every adapter
    python scripts/build_adapters.py --check  # exit 1 if any adapter is stale

Pure standard library.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES = ROOT / "RULES.md"

SOURCE_NOTE = (
    "Generated from RULES.md in the yogosha-skill repository "
    "(https://gitlab.yogosha.com/H4MA/yogosha-skill). Do not edit this file by hand; "
    "edit RULES.md and run scripts/build_adapters.py."
)

# The paragraph in RULES.md that only makes sense inside the repo.
CANONICAL_PARAGRAPH = (
    "Canonical rules for any AI coding agent assisting a bug bounty hunter. This file is the "
    "single source of truth. The per-agent files under `adapters/` embed this same content in "
    "each tool's native format."
)

ADAPTERS = {
    "adapters/claude-md/CLAUDE.md": (
        "# CLAUDE.md - Bug bounty hunter rules of engagement\n\n"
        "Drop this at the root of the repo you drive Claude Code from (or paste into an existing "
        "CLAUDE.md). Claude Code users can instead install the plugin at the root of this repo; "
        "this file is the plain-rules alternative.\n"
    ),
    "adapters/codex/AGENTS.md": (
        "# AGENTS.md - Bug bounty hunter rules of engagement\n\n"
        "Codex reads this file automatically. Copy it to the root of the repo or working "
        "directory you drive Codex from. Follow every rule below for any security-testing or "
        "bug-bounty task.\n"
    ),
    "adapters/continue/rules.md": (
        "# Continue rules - Bug bounty hunter rules of engagement\n\n"
        "Add as a rules block in your Continue config (config.yaml 'rules', or a .continue/rules "
        "file). Follow every rule below for security-testing tasks.\n"
    ),
    "adapters/cursor/.cursor/rules/report-quality.mdc": (
        "---\n"
        "description: Bug bounty hunter rules of engagement and report quality - scope, "
        "non-destructive testing, honest CVSS 4.0, captured proof, report structure.\n"
        "globs:\n"
        "alwaysApply: true\n"
        "---\n"
    ),
    "adapters/windsurf/.windsurfrules": (
        "# .windsurfrules - Bug bounty hunter rules of engagement\n\n"
        "Place at the root of your Windsurf workspace. Cascade applies these rules to "
        "security-testing tasks.\n"
    ),
    "adapters/raw-api/system-prompt.txt": (
        "You are an AI assistant helping a bug bounty hunter. Prepend this as your system "
        "message. Follow every rule.\n"
    ),
}


def rules_body():
    text = RULES.read_text(encoding="utf-8")
    lines = text.split("\n")
    if not lines or not lines[0].startswith("# "):
        sys.exit("RULES.md must start with a level-1 heading")
    body = "\n".join(lines[1:]).lstrip("\n")
    if CANONICAL_PARAGRAPH not in body:
        sys.exit("RULES.md no longer contains the canonical-source paragraph; update build_adapters.py")
    return body.replace(CANONICAL_PARAGRAPH, SOURCE_NOTE)


def render(header, body):
    return header + "\n" + body.rstrip("\n") + "\n"


def main():
    check = "--check" in sys.argv[1:]
    body = rules_body()
    stale = []
    for rel, header in ADAPTERS.items():
        path = ROOT / rel
        want = render(header, body)
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have == want:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("stale adapters (run scripts/build_adapters.py):")
            for rel in stale:
                print("  " + rel)
            sys.exit(1)
        print("adapters in sync with RULES.md")
    else:
        print(f"rewrote {len(stale)} adapter(s); {len(ADAPTERS) - len(stale)} already current")


if __name__ == "__main__":
    main()
